// ---------------------------------------------------------------------------
// Fixed material. Every seed and instant is a constant so the corpus is reproducible:
// a fixture whose bytes depend on when it was generated cannot be regenerated and
// compared, which is the whole point of the writer.
// ---------------------------------------------------------------------------

const TARGET: &str = "https://mcp.example.com/mcp";
const CLIENT_KEY_ID: &str = "client-key-1";
const SERVER_KEY_ID: &str = "server-key-1";
const DELEGATED_KID: &str = "server-key-1/delegated/1";
const ISSUER_KID: &str = "scitt-issuer-1";
const CREATED: i64 = 1_700_000_000;
const EXPIRES: i64 = 1_700_000_300;
const NOW: i64 = 1_700_000_100;
const AWAITING: &str = r#"{"jsonrpc":"2.0","id":1,"result":{"resultType":"input_required"}}"#;
const DONE: &str = r#"{"jsonrpc":"2.0","id":1,"result":{"ok":true}}"#;

fn client_key() -> SigningKey {
    SigningKey::from_seed_bytes(&[11u8; 32])
}

fn server_key() -> SigningKey {
    SigningKey::from_seed_bytes(&[22u8; 32])
}

fn delegated_key() -> SigningKey {
    SigningKey::from_seed_bytes(&[66u8; 32])
}

fn issuer_key() -> SigningKey {
    SigningKey::from_seed_bytes(&[77u8; 32])
}

fn audience() -> AudienceTuple {
    AudienceTuple {
        audience_id: "mcp.example.com".into(),
        target_uri: TARGET.into(),
        route: Some("tools/call".into()),
    }
}

/// The block names the DELEGATED key — the key that actually signed the response — while
/// the trust seam resolves the ROOT the credential chains to.
fn server_signer() -> ActorIdentity {
    ActorIdentity {
        role: "server".into(),
        trust_domain: "example.com".into(),
        subject: "did:example:server".into(),
        keyid: DELEGATED_KID.into(),
    }
}

fn block(continuation: Option<HttpContinuation>) -> HttpRequestEvidenceBlock {
    HttpRequestEvidenceBlock {
        profile: mcp_re_http_profile::PROFILE_TAG.into(),
        audience: audience(),
        artifact_bindings: vec![ArtifactBinding::opaque_digest(
            ArtifactType::OauthDpop,
            b"tok",
        )],
        continuation,
        admission: None,
        admission_assertion: None,
        authorization_decision: None,
    }
}

fn resolver() -> impl Fn(&str, SignerSlot) -> Option<ResolvedActor> {
    move |key_id: &str, slot: SignerSlot| {
        let (role, key) = match (key_id, slot) {
            (CLIENT_KEY_ID, SignerSlot::Request) => ("client", client_key()),
            (SERVER_KEY_ID, SignerSlot::Response) => ("server", server_key()),
            _ => return None,
        };
        Some(ResolvedActor {
            identity: ActorIdentity {
                role: role.into(),
                trust_domain: "example.com".into(),
                subject: format!("did:example:{role}"),
                keyid: key_id.into(),
            },
            verification_key: key.public_key(),
            slot,
        })
    }
}

fn credential() -> String {
    let d = delegated_key();
    let header = mcp_re_http_profile::DelegationHeader {
        typ: mcp_re_http_profile::DELEGATION_TYP.into(),
        alg: mcp_re_http_profile::DELEGATION_ALG.into(),
        kid: SERVER_KEY_ID.into(),
    };
    let claims = mcp_re_http_profile::DelegationClaims {
        iss: "did:example:server".into(),
        iat: CREATED,
        nbf: CREATED,
        exp: EXPIRES,
        jti: "evt-retained".into(),
        aud: mcp_re_http_profile::Audience::One("did:example:server".into()),
        mcp_re_profile: mcp_re_http_profile::PROFILE_TAG.into(),
        mcp_re_audience_hash: "aud-scope-1".into(),
        mcp_re_server_signer: server_signer().actor_id(),
        mcp_re_key_use: mcp_re_http_profile::KEY_USE_RESPONSE_SIGNING.into(),
        delegated_kid: DELEGATED_KID.into(),
        issuer_kid: SERVER_KEY_ID.into(),
        trust_epoch: "epoch-1".into(),
        cnf: mcp_re_http_profile::Cnf {
            jwk: mcp_re_http_profile::DelegatedJwk {
                kty: mcp_re_http_profile::JWK_KTY_OKP.into(),
                crv: mcp_re_http_profile::JWK_CRV_ED25519.into(),
                kid: DELEGATED_KID.into(),
                x: d.public_key().to_b64url(),
            },
        },
    };
    mcp_re_http_profile::issue_delegation_credential(&server_key(), &header, &claims)
}

fn expectations() -> mcp_re_http_profile::DelegationExpectations<'static> {
    mcp_re_http_profile::DelegationExpectations {
        verifier_audiences: &["did:example:server"],
        expected_audience_hash: "aud-scope-1",
        accepted_epochs: &["epoch-1"],
        max_clock_skew: 60,
    }
}

fn nothing_revoked(_: &str) -> bool {
    false
}

fn artifact_material(_: &ArtifactBinding) -> Option<Vec<u8>> {
    Some(b"tok".to_vec())
}

static ARTIFACT_MATERIAL: fn(&ArtifactBinding) -> Option<Vec<u8>> = artifact_material;

fn audit() -> ChainAudit<'static> {
    static AUD: std::sync::OnceLock<AudienceTuple> = std::sync::OnceLock::new();
    ChainAudit {
        expected_audience: AUD.get_or_init(audience),
        artifact_material: &ARTIFACT_MATERIAL,
    }
}

fn to_digest(e: &RequestEvidence) -> RequestEvidenceDigest {
    RequestEvidenceDigest {
        digest_alg: e.digest_alg.clone(),
        digest_value: e.digest_value.clone(),
    }
}

/// Sign one hop with the shipped signers and return it with the two role-labeled handles
/// the next hop's continuation must name.
fn hop(
    nonce: &str,
    continuation: Option<HttpContinuation>,
    body: &str,
) -> (RetainedHop, RequestEvidence, RequestEvidence) {
    let mut request = HttpRequest {
        method: "POST".into(),
        target_uri: TARGET.into(),
        headers: vec![("Content-Type".into(), "application/json".into())],
        body: br#"{"jsonrpc":"2.0","id":1,"method":"tools/call"}"#.to_vec(),
    };
    let req_evidence = mcp_re_http_profile::sign_request_full(
        &mut request,
        &block(continuation),
        &client_key(),
        CLIENT_KEY_ID,
        CREATED,
        EXPIRES,
        nonce,
    )
    .expect("request signs");

    let mut response = HttpResponse {
        status: 200,
        headers: vec![("Content-Type".into(), "application/json".into())],
        body: body.as_bytes().to_vec(),
    };
    // DELEGATED, because that is the only response mode the serving path has.
    mcp_re_http_profile::sign_delegated_response_full(
        &mut response,
        &request,
        &req_evidence,
        &server_signer(),
        &credential(),
        &delegated_key(),
        DELEGATED_KID,
        CREATED,
        EXPIRES,
    )
    .expect("response signs");

    let rsp_evidence = mcp_re_http_profile::Verifier::new(&VerifierPolicy::default(), &resolver())
        .verify_delegated_bound_response(
            &response,
            &request,
            &expectations(),
            &nothing_revoked,
            NOW,
        )
        .expect("response verifies")
        .signature_facts
        .response_signature_base_digest;

    (
        RetainedHop { request, response },
        req_evidence,
        rsp_evidence,
    )
}

/// R0→S0→R1→S1→R2→S2: two non-terminal turns, each re-linking, then a terminal one.
fn three_hop_chain() -> Vec<RetainedHop> {
    let (h0, r0, s0) = hop("retained-n0", None, AWAITING);
    let (h1, r1, s1) = hop(
        "retained-n1",
        Some(HttpContinuation::from_handles(
            to_digest(&r0),
            to_digest(&s0),
            b"state-0",
        )),
        AWAITING,
    );
    let (h2, _, _) = hop(
        "retained-n2",
        Some(HttpContinuation::from_handles(
            to_digest(&r1),
            to_digest(&s1),
            b"state-1",
        )),
        DONE,
    );
    vec![h0, h1, h2]
}

