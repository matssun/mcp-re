//! A retained-evidence corpus MCP-RE produced, and what it establishes — issue #740.
//!
//! # Why this exists beside `interop/`, and does not replace it
//!
//! The frozen `s01` interop corpus records `produced_by: "@transmute/cose 0.3.0 + node
//! crypto Ed25519"`, and *no MCP-RE code produced any of it* is the whole value of that
//! vector: it is the only evidence a foreign implementation reads MCP-RE statements.
//! Regenerating it would destroy a real interop claim to fix a different one, so it stays
//! as it is, demoted in place.
//!
//! What it cannot do is evidence retained-evidence CORRESPONDENCE over a real call. Its
//! `retained-evidence.bin` carries the handles `req-0`/`rsp-0` rather than the submitted
//! messages, so the submission digest is not reproducible from it at all — the artifact
//! cannot be made to bind a submission by any change on the verifier's side. Closing that
//! is a corpus-GENERATION job, and this is it.
//!
//! # What this corpus establishes
//!
//! A three-hop MCP-RE exchange, every hop signed by the shipped signers and verified by
//! the shipped verifier, reconstructed into the record an auditor holds, and committed to
//! by a Signed Statement this crate issued. The statement's `submitted_commitment` is the
//! digest `reconstruct_chain` computed over the SUBMITTED hops, so
//! `verify_retained_evidence` can reach the verdict the frozen corpus cannot:
//! `BoundToVerifiedCall`.
//!
//! # What it does NOT establish
//!
//! Interoperability. Every byte here is MCP-RE's own, which is exactly the property `s01`
//! has and this does not — the two corpora answer different questions and neither
//! substitutes for the other. Nothing here says anything about registration, about a
//! transparency service, or about the confidentiality of retained evidence.
//!
//! # Frozen bytes, and a writer that regenerates them
//!
//! Two directions, the established `write_http_profile_fixtures` pattern:
//!
//!   1. the writer (`write_retained_corpus -- --ignored`) regenerates the corpus with the
//!      project's own implementation, so committed bytes and regenerated bytes are
//!      compared rather than assumed;
//!   2. the frozen runner verifies the COMMITTED bytes, so a change that alters what the
//!      implementation emits is visible as a diff rather than absorbed silently.
//!
//! Regenerate: `cargo test -p mcp-re-conformance --test scitt_retained_corpus_test \
//!   write_retained_corpus -- --ignored --exact`

