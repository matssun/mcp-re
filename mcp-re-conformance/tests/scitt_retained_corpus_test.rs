/// The verdict the frozen corpus cannot reach, over bytes MCP-RE produced.
///
/// `BoundToVerifiedCall` is the whole point: the statement identifies a submission, the
/// retained messages reproduce that identity, and every hop verified — so the record is
/// bound to a call that happened rather than merely to bytes an issuer saw.
#[test]
fn the_committed_corpus_binds_its_statement_to_a_verified_call() {
    let hops = retained_hops();
    assert_eq!(hops.len(), 3, "the corpus is the three-hop chain");
    let reconstruction = reconstruct(&hops);
    assert_eq!(
        reconstruction.label(),
        &ChainLabel::Complete,
        "every hop of the committed corpus must verify"
    );
    assert!(
        !reconstruction.submitted_commitment().is_empty(),
        "a reconstruction from retained MESSAGES identifies its submission"
    );

    let statement = statement();
    assert!(
        statement.commitment().identifies_a_submission(),
        "the committed statement is a post-revision record"
    );
    assert_eq!(
        verify_retained_evidence(statement.commitment(), &reconstruction, None, None)
            .expect("the committed corpus corresponds"),
        RetainedCorrespondence::BoundToVerifiedCall
    );
}

/// A tampered retained body is refused, and refused for the right reason.
///
/// The submission digest is over the SUBMITTED bytes, so altering one changes the identity
/// the statement named — before any question of whether the altered hop still verifies.
#[test]
fn a_tampered_retained_body_no_longer_corresponds() {
    let mut hops = retained_hops();
    hops[2].response.body.push(b' ');
    let reconstruction = reconstruct(&hops);
    let untampered = reconstruct(&retained_hops());
    assert_ne!(
        reconstruction.submitted_commitment(),
        untampered.submitted_commitment(),
        "a changed submitted byte must change the identity"
    );
    verify_retained_evidence(statement().commitment(), &reconstruction, None, None)
        .expect_err("a tampered record must not correspond");
}

/// A truncated record is refused even though its prefix matches.
///
/// The label is inside what the commitment covers, so a record that stops early is a
/// different record — which is the property the whole `submitted_commitment` revision
/// exists to make checkable on the hops after the verified prefix.
#[test]
fn a_truncated_corpus_no_longer_corresponds() {
    let hops = retained_hops();
    let reconstruction = reconstruct(&hops[..2]);
    verify_retained_evidence(statement().commitment(), &reconstruction, None, None)
        .expect_err("a truncated record must not correspond");
}

/// The committed bytes are what this implementation emits today.
///
/// Not a tautology: it compares the FROZEN artifact against a fresh generation, so a change
/// in what MCP-RE produces shows up here rather than being absorbed by regenerating the
/// corpus and the expectation together.
#[test]
fn the_committed_bytes_are_the_ones_this_implementation_produces() {
    let (regenerated_hops, regenerated_statement) = generate();
    assert_eq!(
        serde_json::to_vec_pretty(&regenerated_hops).expect("hops encode"),
        artifact("retained-hops.json"),
        "the committed retained hops are not what this implementation emits; regenerate \
         with `write_retained_corpus -- --ignored --exact` and review the diff"
    );
    assert_eq!(
        regenerated_statement,
        artifact("signed-statement.cbor"),
        "the committed statement is not what this implementation emits"
    );
}

