/// One retained HTTP message, as the artifact records it.
///
/// The MESSAGES, not handles. That is the whole difference from the frozen `s01` artifact
/// and the reason a submission digest is reproducible here at all.
#[derive(serde::Serialize, serde::Deserialize)]
struct WireMessage {
    #[serde(skip_serializing_if = "Option::is_none")]
    method: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    target_uri: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    status: Option<u16>,
    headers: Vec<(String, String)>,
    body_b64: String,
}

#[derive(serde::Serialize, serde::Deserialize)]
struct WireHop {
    request: WireMessage,
    response: WireMessage,
}

fn to_wire_request(r: &HttpRequest) -> WireMessage {
    WireMessage {
        method: Some(r.method.clone()),
        target_uri: Some(r.target_uri.clone()),
        status: None,
        headers: r.headers.clone(),
        body_b64: mcp_re_core::b64url_encode(&r.body),
    }
}

fn to_wire_response(r: &HttpResponse) -> WireMessage {
    WireMessage {
        method: None,
        target_uri: None,
        status: Some(r.status),
        headers: r.headers.clone(),
        body_b64: mcp_re_core::b64url_encode(&r.body),
    }
}

fn from_wire_request(w: &WireMessage) -> HttpRequest {
    HttpRequest {
        method: w.method.clone().expect("a retained request names a method"),
        target_uri: w
            .target_uri
            .clone()
            .expect("a retained request names a target"),
        headers: w.headers.clone(),
        body: mcp_re_core::b64url_decode(&w.body_b64).expect("body decodes"),
    }
}

fn from_wire_response(w: &WireMessage) -> HttpResponse {
    HttpResponse {
        status: w.status.expect("a retained response names a status"),
        headers: w.headers.clone(),
        body: mcp_re_core::b64url_decode(&w.body_b64).expect("body decodes"),
    }
}

/// Where the corpus lives, under Cargo and under Bazel.
///
/// The same dual-mode bridge the interop corpus uses: Bazel stages the vectors as runfiles
/// and names the manifest through `MCP_RE_SCITT_RETAINED_MANIFEST`, so the directory is
/// derived from that rather than from `CARGO_MANIFEST_DIR`, which is a source path the
/// sandbox does not have.
fn corpus_dir() -> PathBuf {
    if let Ok(rel) = std::env::var("MCP_RE_SCITT_RETAINED_MANIFEST") {
        for key in ["TEST_SRCDIR", "RUNFILES_DIR"] {
            if let Ok(root) = std::env::var(key) {
                let candidate = std::path::Path::new(&root).join(&rel);
                if candidate.exists() {
                    return candidate.parent().expect("manifest parent").to_path_buf();
                }
            }
        }
        let candidate = PathBuf::from(&rel);
        if candidate.exists() {
            return candidate.parent().expect("manifest parent").to_path_buf();
        }
        panic!("MCP_RE_SCITT_RETAINED_MANIFEST set but runfile not found (rel={rel})");
    }
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("vectors")
        .join("scitt")
        .join("retained")
}

fn artifact(name: &str) -> Vec<u8> {
    std::fs::read(corpus_dir().join(name)).unwrap_or_else(|e| panic!("{name}: {e}"))
}

fn retained_hops() -> Vec<RetainedHop> {
    let wire: Vec<WireHop> =
        serde_json::from_slice(&artifact("retained-hops.json")).expect("retained hops parse");
    wire.iter()
        .map(|h| RetainedHop {
            request: from_wire_request(&h.request),
            response: from_wire_response(&h.response),
        })
        .collect()
}

fn statement() -> SignedStatement {
    SignedStatement::from_cose(&artifact("signed-statement.cbor")).expect("statement parses")
}

/// Reconstruct the record an auditor holds from the retained MESSAGES.
fn reconstruct(hops: &[RetainedHop]) -> mcp_re_http_profile::chain::ChainReconstruction {
    let policy = VerifierPolicy::default();
    let resolve = resolver();
    let verifier = mcp_re_http_profile::Verifier::new(&policy, &resolve);
    reconstruct_chain(
        hops,
        &verifier,
        &expectations(),
        &audit(),
        &nothing_revoked,
        NOW,
    )
}

fn sign_statement(bytes: &[u8]) -> Result<Vec<u8>, HttpProfileError> {
    // `SigningKey::sign` answers base64url; the COSE structure carries raw signature bytes.
    mcp_re_core::b64url_decode(&issuer_key().sign(bytes))
        .map_err(|_| HttpProfileError::MalformedEvidence("issuer signature encoding"))
}

