/// Build the corpus from the shipped signers, verifier and issuer.
fn generate() -> (Vec<WireHop>, Vec<u8>) {
    let hops = three_hop_chain();
    let reconstruction = reconstruct(&hops);
    assert_eq!(
        reconstruction.label(),
        &ChainLabel::Complete,
        "the generated chain must verify end to end"
    );
    let commitment = EvidenceCommitment::from_reconstruction(&reconstruction, None, None);
    let statement = mcp_re_http_profile::scitt::issue_signed_statement(
        ISSUER_KID,
        commitment,
        NOW,
        sign_statement,
    )
    .expect("the statement issues");
    let wire = hops
        .iter()
        .map(|h| WireHop {
            request: to_wire_request(&h.request),
            response: to_wire_response(&h.response),
        })
        .collect();
    (wire, statement.to_cose().to_vec())
}

#[test]
#[ignore = "corpus writer; run with --ignored to regenerate"]
fn write_retained_corpus() {
    let dir = corpus_dir();
    std::fs::create_dir_all(&dir).expect("corpus dir");
    let (hops, statement) = generate();
    std::fs::write(
        dir.join("retained-hops.json"),
        serde_json::to_vec_pretty(&hops).expect("hops encode"),
    )
    .expect("write hops");
    std::fs::write(dir.join("signed-statement.cbor"), &statement).expect("write statement");
    let manifest = serde_json::json!({
        "schema": "mcp-re-scitt-retained/v1",
        "produced_by": "mcp-re-conformance write_retained_corpus (this repository)",
        "establishes": "retained-evidence correspondence over a real MCP-RE multi-hop call: \
                        the statement identifies the submission the retained messages \
                        reproduce, and every hop verified",
        "does_not_establish": "interoperability — every byte here is MCP-RE's own; that is \
                               the interop corpus's question and this does not answer it. \
                               Nothing about registration, a transparency service, or the \
                               confidentiality of retained evidence.",
        "artifacts": {
            "retained-hops.json": hex_sha256(
                &serde_json::to_vec_pretty(&hops).expect("hops encode")
            ),
            "signed-statement.cbor": hex_sha256(&statement),
        }
    });
    std::fs::write(
        dir.join("manifest.json"),
        serde_json::to_vec_pretty(&manifest).expect("manifest encodes"),
    )
    .expect("write manifest");
    eprintln!("wrote the retained corpus into {}", dir.display());
}

fn hex_sha256(bytes: &[u8]) -> String {
    use sha2::Digest;
    let mut hasher = sha2::Sha256::new();
    hasher.update(bytes);
    hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// The manifest is a description of the artifacts, and it must describe THESE artifacts.
#[test]
fn the_manifest_describes_the_committed_artifacts() {
    let manifest: serde_json::Value =
        serde_json::from_slice(&artifact("manifest.json")).expect("manifest parses");
    assert_eq!(
        manifest["artifacts"]["retained-hops.json"].as_str(),
        Some(hex_sha256(&artifact("retained-hops.json")).as_str())
    );
    assert_eq!(
        manifest["artifacts"]["signed-statement.cbor"].as_str(),
        Some(hex_sha256(&artifact("signed-statement.cbor")).as_str())
    );
    assert!(
        manifest["produced_by"]
            .as_str()
            .is_some_and(|s| s.contains("this repository")),
        "the manifest must say whose bytes these are — it is the one thing that \
         distinguishes this corpus from the interop one"
    );
}
